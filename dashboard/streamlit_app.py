import os
from datetime import datetime, timezone

import pandas as pd
import plotly.express as px
import requests
import streamlit as st

st.set_page_config(
    page_title="Weather Intelligence",
    page_icon="🌦️",
    layout="wide",
    initial_sidebar_state="collapsed",
)

API = os.getenv("API_BASE_URL", "http://localhost:8000").rstrip("/")
st.markdown("""
<style>
    .block-container {max-width: 1180px; padding-top: 2rem; padding-bottom: 3rem;}
    [data-testid="stMetric"] {background: var(--secondary-background-color); padding: 15px 17px; border-radius: 12px; border: 1px solid rgba(128,128,128,.16);}
    [data-testid="stMetricLabel"] p {font-size: .86rem;}
    div[data-testid="stTabs"] button {font-weight: 600;}
    .hero-note {color: var(--secondary-text-color); font-size: .95rem; margin-top: -.5rem;}
    .section-note {color: var(--secondary-text-color); font-size: .88rem;}
</style>
""", unsafe_allow_html=True)

st.title("🌦️ Weather Intelligence")
st.markdown('<p class="hero-note">Local weather, calibrated forecasts and clear insights for the next three days.</p>', unsafe_allow_html=True)

with st.form("location_form"):
    c1, c2 = st.columns([4, 1])
    with c1:
        place = st.text_input(
            "Search a city or location",
            value=st.session_state.get("place", "Mysuru, Karnataka, India"),
            placeholder="e.g. Mysuru, Karnataka",
            help="Enter a city, town or recognised location in India.",
        )
    with c2:
        st.markdown("<div style='height: 27px'></div>", unsafe_allow_html=True)
        submitted = st.form_submit_button("Get forecast", type="primary", use_container_width=True)

if submitted:
    if not place.strip():
        st.warning("Please enter a location.")
    else:
        try:
            with st.spinner(f"Getting weather for {place.strip()}…"):
                weather_response = requests.get(
                    f"{API}/api/weather/location",
                    params={"place": place.strip(), "history_days": 7},
                    timeout=60,
                )
                weather_response.raise_for_status()
                weather_data = weather_response.json()

                forecast_response = requests.get(
                    f"{API}/api/predictions/three-day",
                    params={"place": place.strip()},
                    timeout=60,
                )
                forecast_response.raise_for_status()
                forecast_data = forecast_response.json()

            st.session_state["place"] = place.strip()
            st.session_state["weather_data"] = weather_data
            st.session_state["forecast_data"] = forecast_data
            st.session_state.pop("load_error", None)
        except requests.RequestException as exc:
            detail = str(exc)
            response = getattr(exc, "response", None)
            if response is not None:
                try:
                    payload = response.json()
                    detail = payload.get("detail", response.text)
                except ValueError:
                    detail = response.text or detail
            st.session_state["load_error"] = detail
        except (KeyError, TypeError, ValueError) as exc:
            st.session_state["load_error"] = f"The API returned an unexpected response: {exc}"

if st.session_state.get("load_error"):
    st.error("We couldn't load the weather data.")
    st.caption(st.session_state["load_error"])
    st.info("Check the location spelling and try again. If the service has just woken up, the first request may take a little longer.")

weather = st.session_state.get("weather_data")
result = st.session_state.get("forecast_data")

if not weather or not result:
    st.divider()
    st.subheader("Your forecast starts here")
    st.write("Search for a location above to see current conditions and the model's 1-, 2- and 3-day forecasts.")
    st.caption("Forecasts are generated by the saved India calibration model. The first request may take longer if the free backend is waking up.")
    st.stop()

location = weather.get("location", {})
current = weather.get("current", {})
predictions = result.get("predictions", [])
history_rows = weather.get("history", [])

location_name = ", ".join(
    str(x) for x in [location.get("name"), location.get("state"), location.get("country")] if x
)
st.subheader(f"📍 {location_name or st.session_state.get('place', 'Selected location')}")
st.caption(f"Current conditions · {current.get('condition', 'Latest available observation').title()}")

m1, m2, m3, m4 = st.columns(4)
m1.metric("Temperature", f"{current.get('temperature_c', '—')} °C", help="Latest current-weather observation")
m2.metric("Feels like", f"{current.get('feels_like_c', '—')} °C")
m3.metric("Humidity", f"{current.get('humidity_pct', '—')}%")
m4.metric("Wind speed", f"{current.get('wind_speed_ms', '—')} m/s")

tab_overview, tab_forecast, tab_history, tab_model = st.tabs(
    ["☀️ Overview", "📅 3-day forecast", "📈 Recent weather", "🧪 Model information"]
)

with tab_overview:
    st.subheader("The next three days")
    if not predictions:
        st.warning("The API did not return forecast rows for this location.")
    else:
        cards = st.columns(len(predictions))
        for col, item in zip(cards, predictions):
            with col:
                day = item.get("horizon_days", "?")
                st.markdown(f"**Day {day}**")
                st.metric("Temperature", f"{item.get('temperature_c', float('nan')):.1f} °C")
                st.metric("Rain chance", f"{item.get('rainfall_probability', 0) * 100:.0f}%")
                st.caption(
                    f"💧 {item.get('rainfall_mm', 0):.1f} mm rain  ·  "
                    f"💨 {item.get('wind_speed_ms', 0):.1f} m/s wind"
                )
                st.caption(f"Humidity: {item.get('humidity_pct', 0):.0f}%")
    st.markdown("---")
    st.markdown("**How to read the forecast**")
    st.caption("Rain chance is the model's estimated probability of measurable rainfall. Rainfall amount is a separate estimate in millimetres. A higher rain chance does not guarantee rain at your exact location.")

with tab_forecast:
    st.subheader("Forecast details")
    st.markdown('<p class="section-note">Model-adjusted estimates at approximately 24, 48 and 72 hours ahead.</p>', unsafe_allow_html=True)
    if predictions:
        forecast = pd.DataFrame(predictions)
        display_columns = {
            "horizon_days": "Days ahead",
            "date": "Date",
            "temperature_c": "Temperature (°C)",
            "rainfall_probability": "Rain chance",
            "rainfall_mm": "Rainfall (mm)",
            "humidity_pct": "Humidity (%)",
            "wind_speed_ms": "Wind (m/s)",
        }
        available = [key for key in display_columns if key in forecast.columns]
        display = forecast[available].rename(columns=display_columns).copy()
        if "Rain chance" in display:
            display["Rain chance"] = (display["Rain chance"] * 100).round(1).astype(str) + "%"
        st.dataframe(display, use_container_width=True, hide_index=True)

        left, right = st.columns(2)
        with left:
            if "temperature_c" in forecast:
                fig = px.line(forecast, x="date", y="temperature_c", markers=True,
                              labels={"date": "Date", "temperature_c": "Temperature (°C)"},
                              title="🌡️ Temperature")
                fig.update_layout(margin=dict(l=10, r=10, t=55, b=10), height=300)
                st.plotly_chart(fig, use_container_width=True)
        with right:
            if "rainfall_probability" in forecast:
                rain_plot = forecast.assign(rain_chance_pct=forecast["rainfall_probability"] * 100)
                fig = px.bar(rain_plot, x="date", y="rain_chance_pct",
                             labels={"date": "Date", "rain_chance_pct": "Rain chance (%)"},
                             title="🌧️ Chance of rain", range_y=[0, 100])
                fig.update_layout(margin=dict(l=10, r=10, t=55, b=10), height=300)
                st.plotly_chart(fig, use_container_width=True)
        left, right = st.columns(2)
        with left:
            if "humidity_pct" in forecast:
                fig = px.line(forecast, x="date", y="humidity_pct", markers=True,
                              labels={"date": "Date", "humidity_pct": "Humidity (%)"},
                              title="💧 Humidity")
                fig.update_layout(margin=dict(l=10, r=10, t=55, b=10), height=300)
                st.plotly_chart(fig, use_container_width=True)
        with right:
            if "wind_speed_ms" in forecast:
                fig = px.line(forecast, x="date", y="wind_speed_ms", markers=True,
                              labels={"date": "Date", "wind_speed_ms": "Wind speed (m/s)"},
                              title="💨 Wind speed")
                fig.update_layout(margin=dict(l=10, r=10, t=55, b=10), height=300)
                st.plotly_chart(fig, use_container_width=True)
    else:
        st.info("No forecast details are available yet.")

with tab_history:
    st.subheader("Recent weather")
    history = pd.DataFrame(history_rows)
    if not history.empty:
        if {"date", "temperature_c"}.issubset(history.columns):
            fig = px.line(history, x="date", y="temperature_c", markers=True,
                          labels={"date": "Date", "temperature_c": "Temperature (°C)"},
                          title="Recent daily temperature")
            fig.update_layout(margin=dict(l=10, r=10, t=55, b=10), height=330)
            st.plotly_chart(fig, use_container_width=True)
        st.dataframe(history, use_container_width=True, hide_index=True)
    else:
        st.info("Recent weather history is not available for this location.")

with tab_model:
    st.subheader("About this forecast")
    st.write("The app uses a saved India-wide, fixed-lead calibration model. It adjusts the underlying forecast for 1-, 2- and 3-day lead times; it does not train a model during your visit.")
    st.caption(f"Model version: {result.get('model_version', 'Not reported')}")
    st.caption(result.get("model_mode", "India fixed-lead calibrated model"))
    st.warning("Evaluation targets were Open-Meteo historical reanalysis, not independent weather-station observations. Metrics should therefore be interpreted as reanalysis-based validation, not proof of station-level accuracy.")
    with st.expander("View model validation metrics"):
        try:
            metrics_response = requests.get(f"{API}/api/models/metrics", timeout=20)
            metrics_response.raise_for_status()
            st.json(metrics_response.json())
        except requests.RequestException as exc:
            st.error(f"Could not load model metrics: {exc}")

st.divider()
st.caption("Weather Intelligence · Forecasts are estimates and should not be used as the sole basis for safety-critical decisions.")
